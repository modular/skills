class _RenameName(ast.NodeTransformer):
    def __init__(self, old: str, new: str) -> None:
        self.old = old
        self.new = new

    def visit_Name(self, node: ast.Name) -> ast.Name:
        if node.id == self.old:
            node.id = self.new
        return node


_HF_CONFIG_NAMES = frozenset({"huggingface_config", "hf_config", "text_config"})
"""Names that hold a Hugging Face config in donor code."""

ROPE_THETA_IMPORT = ImportedName(
    "max.pipelines.lib.pipeline_variants.utils", "get_rope_theta"
)
"""Reads ``rope_theta`` under both Transformers 4 and Transformers 5."""


class _RopeThetaRewrite(ast.NodeTransformer):
    """Rewrites ``<hf config>.rope_theta`` to ``get_rope_theta(<hf config>)``.

    Transformers 5 moves ``rope_theta`` into ``rope_parameters``, so a donor
    that reads the attribute raises ``AttributeError`` there, and a port
    copied from it inherits the error.
    """

    def __init__(self) -> None:
        self.rewrote = False

    def visit_Attribute(self, node: ast.Attribute) -> ast.AST:
        self.generic_visit(node)
        holder = node.value
        name = (
            holder.id
            if isinstance(holder, ast.Name)
            else holder.attr
            if isinstance(holder, ast.Attribute)
            else None
        )
        if node.attr != "rope_theta" or name not in _HF_CONFIG_NAMES:
            return node
        if not isinstance(node.ctx, ast.Load):
            return node
        self.rewrote = True
        return ast.copy_location(
            ast.Call(
                func=ast.Name(ROPE_THETA_IMPORT.name, ast.Load()),
                args=[holder],
                keywords=[],
            ),
            node,
        )


@dataclass
class _BodyImports:
    """Imports a copied method body needs, split the way isort groups them."""

    stdlib: list[str]
    """``import x`` lines from the standard library."""
    third_party: list[str]
    """``import x`` lines from anywhere else."""
    names: list[tuple[str, str]]
    """``(module, name)`` pairs for ``from module import name``."""
    warnings: list[str] = field(default_factory=list)
    """Names the body reads that no import or definition provides."""


def _plain_import(parsed: ParsedModule, name: str) -> str | None:
    """The ``import x`` / ``import x as y`` line that binds ``name``."""
    for node in parsed.tree.body:
        if not isinstance(node, ast.Import):
            continue
        for alias in node.names:
            bound = alias.asname or alias.name.split(".")[0]
            if bound != name:
                continue
            if alias.asname:
                return f"import {alias.name} as {alias.asname}"
            return f"import {alias.name}"
    return None


def _render_instantiate(donor: Donor, short: str) -> tuple[str, _BodyImports]:
    """Render the donor's ``_instantiate_module`` building ``short``.

    Returns the method source and the imports its body needs from outside
    the port package.
    """
    parsed, donor_fn = donor.instantiate
    fn = copy.deepcopy(donor_fn)
    fn = _RenameName(donor.module.name, short).visit(fn)
    rope_theta = _RopeThetaRewrite()
    fn = rope_theta.visit(fn)
    ast.fix_missing_locations(fn)
    body = [
        stmt
        for stmt in fn.body
        if not (
            isinstance(stmt, ast.Expr)
            and isinstance(stmt.value, ast.Constant)
            and isinstance(stmt.value.value, str)
        )
    ]
    fn.body = body

    imports = _BodyImports(stdlib=[], third_party=[], names=[])
    args = fn.args
    params = {
        a.arg for a in (*args.posonlyargs, *args.args, *args.kwonlyargs)
    } | {a.arg for a in (args.vararg, args.kwarg) if a is not None}
    reads = dict.fromkeys(node.id for node in free_names(fn.body, params))
    for name in reads:
        if name == short:
            continue
        if rope_theta.rewrote and name == ROPE_THETA_IMPORT.name:
            imports.names.append(
                (ROPE_THETA_IMPORT.module, ROPE_THETA_IMPORT.name)
            )
            continue
        plain = _plain_import(parsed, name)
        if plain is not None:
            top = plain.split()[1].split(".")[0]
            if top in sys.stdlib_module_names:
                imports.stdlib.append(plain)
            else:
                imports.third_party.append(plain)
            continue
        imported = parsed.imports.get(name)
        if imported is None and parsed.defines(name):
            imported = ImportedName(parsed.module, name)
        if imported is None:
            imports.warnings.append(
                f"{donor.model.name}._instantiate_module uses {name!r}, "
                f"which scaffold.py could not trace to an import. Add the "
                f"import to model.py by hand."
            )
            continue
        imports.names.append(
            (imported.module, _import_name(imported.name, name))
        )

    param = fn.args.args[1].arg if len(fn.args.args) > 1 else "model_config"
    lines = []
    for stmt in body:
        lines.extend(ast.unparse(stmt).splitlines())
    rendered = "\n".join(f"        {line}" for line in lines)
    source = (
        f"    def _instantiate_module(self, {param}: Any) -> Any:\n"
        f"        # Same arguments and placement as "
        f"{donor.model.name}._instantiate_module.\n"
        f"{rendered}\n"
    )
    return source, imports


def render_model(
    *, slug: str, donor: Donor, short: str
) -> tuple[str, list[str]]:
    """Render model.py. Returns the file and its warnings."""
    model = donor.model.name
    alias = _donor_alias(model, f"{short}Model")
    instantiate, body_imports = _render_instantiate(donor, short)
    stdlib = _render_section(
        plain=body_imports.stdlib,
        pairs=[("typing", "Any"), ("typing", "ClassVar")],
    )
    imports = _render_section(
        plain=body_imports.third_party,
        pairs=[
            (donor.model.module, _import_name(model, alias)),
            *body_imports.names,
        ],
    )
    local = _render_relative_imports(
        [("model_config", f"{short}Config"), (slug, short)]
    )
    if donor.builds_config:
        config_doc = (
            f"``_create_model_config`` re-types\n"
            f"the donor's config as ``{short}Config`` and "
        )
        create = (
            f"    def _create_model_config(self, state_dict: dict[str, Any]) "
            f"-> Any:\n"
            f"        donor_config = super()._create_model_config(state_dict)\n"
            f"        return {short}Config.from_donor(donor_config, "
            f"self.huggingface_config)\n\n"
        )
    else:
        # The donor returns no config, so there is nothing to re-type.
        config_doc = "The donor builds no\nconfig object, and "
        create = ""
    return (
        f'''{_GENERATED_HEADER}"""Pipeline model for the {short} port.

Subclasses {model} from the {donor.slug} donor, a ModuleV3 pipeline model:
the base ``load_model`` builds the root module under ``F.lazy()`` and
compiles it with the checkpoint weights. {config_doc}``_instantiate_module`` builds
the port's root module ``{short}``.
"""

from __future__ import annotations

{stdlib}

{imports}

{local}


class {short}Model({alias}):
    model_config_cls: ClassVar[type[Any]] = {short}Config

{create}{instantiate}''',
        body_imports.warnings,
    )


