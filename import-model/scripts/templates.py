_GENERATED_HEADER = (
    "# Generated by scaffold.py. Edit the TODOs as you discover deltas.\n"
)


def _import_sort_key(name: str) -> tuple[int, str]:
    """isort's ``order-by-type``: CONSTANTS, then Classes, then functions."""
    bare = name.split(" as ")[0]
    if bare.isupper() and len(bare) > 1:
        return 0, bare
    if bare[:1].isupper():
        return 1, bare
    return 2, bare


def _render_section(
    plain: Iterable[str] = (), pairs: Iterable[tuple[str, str]] = ()
) -> str:
    """Render one isort section of imports, the way ruff's I001 orders it.

    ``plain`` holds whole ``import x`` lines and ``pairs`` holds
    ``(module, name)`` for ``from module import name``. Plain imports come
    first, then the ``from`` imports, each sorted by module. Names from the
    same module merge into one statement. Sorting the whole section matters
    because donor names can live anywhere (for example
    ``max.pipelines.architectures.deepseekV3.memory_planner``), and splicing
    one at a fixed position fails I001.
    """
    lines = sorted(set(plain), key=lambda line: line.split()[1].lower())
    by_module: dict[str, set[str]] = {}
    for module, name in pairs:
        by_module.setdefault(module, set()).add(name)
    for module in sorted(by_module, key=str.lower):
        names = sorted(by_module[module], key=_import_sort_key)
        line = f"from {module} import {', '.join(names)}"
        if len(line) > 80:
            body = "".join(f"    {name},\n" for name in names)
            line = f"from {module} import (\n{body})"
        lines.append(line)
    return "\n".join(lines)


def _render_relative_imports(pairs: Iterable[tuple[str, str]]) -> str:
    """Render ``from .module import name`` lines for the port's own files."""
    return "\n".join(
        f"from .{module} import {name}"
        for module, name in sorted(pairs, key=lambda p: p[0].lower())
    )


def _donor_alias(donor_name: str, port_name: str) -> str:
    """Import alias for a donor class whose name the port class reuses.

    Scaffolding ``Olmo3ForCausalLM`` from ``olmo3`` would otherwise define
    ``class Olmo3Model(Olmo3Model)``.
    """
    return f"Donor{donor_name}" if donor_name == port_name else donor_name


def _import_name(donor_name: str, alias: str) -> str:
    return donor_name if alias == donor_name else f"{donor_name} as {alias}"


